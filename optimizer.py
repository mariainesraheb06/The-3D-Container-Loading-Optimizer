"""
optimizer.py  ─  3D Container Loading Optimizer
================================================
Shared algorithm module used by both the Jupyter Notebook and the Desktop App.

Algorithms implemented
──────────────────────
  1. Greedy Best-Fit Decreasing (BFD)
  2. Genetic Algorithm           (GA)
  3. Simulated Annealing         (SA)

All three algorithms use the same core decoder (pack_sequence) which implements
a Deepest-Bottom-Left-Fill strategy with candidate-point enumeration.
"""

