@dataclass
class Box:
    """A single rectangular box to be packed."""

    id: int
    length: float
    width: float
    height: float
    weight_kg: float
    fragile: bool = False

    @property
    def volume(self) -> float:
        return self.length * self.width * self.height

    def get_orientations(self) -> List[Tuple[float, float, float]]:
        """Return all physically valid orientations (L, W, H permutations)."""
        l, w, h = self.length, self.width, self.height
        if self.fragile:
            # Fragile: only rotate in the horizontal plane (height stays fixed)
            return [(l, w, h), (w, l, h)]
        return [
            (l, w, h), (l, h, w),
            (w, l, h), (w, h, l),
            (h, l, w), (h, w, l),
        ]

    def orientation_labels(self) -> List[str]:
        return [f"{o[0]}×{o[1]}×{o[2]} cm" for o in self.get_orientations()]

    def __repr__(self) -> str:
        return (f"Box(id={self.id}, {self.length}×{self.width}×{self.height}, "
                f"wt={self.weight_kg}kg, fragile={self.fragile})")


@dataclass
class Container:
    """The shipping container to pack boxes into."""

    name: str
    length: float
    width: float
    height: float

    @property
    def volume(self) -> float:
        return self.length * self.width * self.height

    def __str__(self) -> str:
        return f"{self.name} ({self.length}×{self.width}×{self.height} cm)"


