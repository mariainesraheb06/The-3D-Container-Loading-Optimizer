def draw_box_3d(ax, pos, dim, color, alpha=0.55, highlight=False):
    """Draw a single 3D box as a Poly3DCollection on a matplotlib Axes3D."""
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection
    x, y, z = pos;  l, w, h = dim
    xx = [x, x+l, x+l, x, x, x+l, x+l, x]
    yy = [y, y,   y+w, y+w, y, y,   y+w, y+w]
    zz = [z, z,   z,   z,   z+h, z+h, z+h, z+h]
    faces = [[0,1,2,3],[4,5,6,7],[0,1,5,4],[2,3,7,6],[0,3,7,4],[1,2,6,5]]
    poly = Poly3DCollection(
        [[[xx[i], yy[i], zz[i]] for i in f] for f in faces],
        alpha=alpha,
        facecolor=color,
        edgecolor="#FFD700" if highlight else "#333333",
        linewidth=2.0 if highlight else 0.3,
    )
    ax.add_collection3d(poly)
